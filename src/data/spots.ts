export function nearestTown(lat: number, lng: number) {
  let best: { town: string; miles: number } | null = null;
  for (const [town, point] of Object.entries(TOWN_POINTS)) {
    const miles = haversine(lat, lng, point.lat, point.lng);
    if (!best || miles < best.miles) best = { town, miles };
  }
  if (!best || best.miles > 45) return null;
  return best;
}

function haversine(lat1: number, lng1: number, lat2: number, lng2: number) {
  const r = 3958.8;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLng = ((lng2 - lng1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos((lat1 * Math.PI) / 180) * Math.cos((lat2 * Math.PI) / 180) * Math.sin(dLng / 2) ** 2;
  return 2 * r * Math.asin(Math.sqrt(a));
}
