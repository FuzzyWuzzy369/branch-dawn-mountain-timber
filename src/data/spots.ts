type Row = Omit<Spot, "id">;

function idFor(name: string, address: string) {
  return `${name} ${address}`
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function row(entry: Row): Spot {
  return { ...entry, id: idFor(entry.name, entry.address) };
}

