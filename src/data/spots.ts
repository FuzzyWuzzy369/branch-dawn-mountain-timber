function isChainFastFood(name: string) {
  const key = nameKey(name);
  if (key.startsWith("freddy")) return false;
  if (key.includes("museum")) return false;
  for (const chain of CHAIN_FAST_FOOD) {
    if (key === chain) return true;
    if (chain.length >= 8 && key.includes(chain)) return true;
  }
  return false;
}

function streetKey(address: string) {
  const street = address.toLowerCase().split(",")[0] ?? "";
  const words = street
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .split(/\s+/)
    .filter((word) => !/^\d+\.\d+$/.test(word))
    .map((word) =>
      ({
        west: "w",
        east: "e",
        north: "n",
        south: "s",
        street: "st",
        avenue: "ave",
        road: "rd",
        drive: "dr",
        boulevard: "blvd",
      })[word] ?? word,
    );
  return words.join("");
}

function sameRoom(
  leftName: string,
  leftAddress: string,
  leftTown: string,
  rightName: string,
  rightAddress: string,
  rightTown: string,
) {
  if (leftTown !== rightTown) return false;
  const left = nameKey(leftName);
  const right = nameKey(rightName);
  const names =
    left === right || (left.length >= 5 && right.length >= 5 && (left.includes(right) || right.includes(left)));
  if (!names) return false;
  const leftStreet = streetKey(leftAddress);
  const rightStreet = streetKey(rightAddress);
  const vague = !/\d/.test(leftAddress.split(",")[0] ?? "") || !/\d/.test(rightAddress.split(",")[0] ?? "");
  if (vague) return true;
  return leftStreet.length >= 6 && leftStreet === rightStreet;
}

